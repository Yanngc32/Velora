#!/usr/bin/env python3
"""Generates the Velora mark as SVG (packaging/velora-icon.svg) and as Android vector
drawables, from one definition so they never diverge.

Only effects VectorDrawable supports are used: linear/radial gradients and gradient strokes
(no blur), layered for volume: a glow under each panel, a shade where the front panel covers
the back one, a glassy overlap and light catching the top edges.
"""
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
GREEN = "M28.1,44.1 Q25.4,36.5 33.3,38.0 L41.9,39.6 Q49.7,41.0 53.1,48.3 L59.5,62.2 Q62.8,69.5 55.7,73.0 L48.5,76.6 Q41.3,80.2 38.6,72.7 Z"
PURPLE = "M49.1,45.3 Q45.8,38.1 53.0,34.6 L60.1,31.3 Q67.3,27.8 69.8,35.4 L80.1,66.6 Q82.6,74.2 74.7,72.8 L68.4,71.7 Q60.5,70.3 57.2,63.0 Z"
GLASS = "M45.9,42.8 Q45.2,39.9 48.1,40.7 L56.7,43.0 Q59.6,43.8 60.2,46.7 L64.1,65.7 Q64.7,68.7 61.7,68.9 L54.4,69.5 Q51.4,69.8 50.8,66.8 Z"
GLOW_GREEN = "M40,58 m-26,0 a26,26 0 1,0 52,0 a26,26 0 1,0 -52,0"
GLOW_PURPLE = "M68,52 m-26,0 a26,26 0 1,0 52,0 a26,26 0 1,0 -52,0"

# (name, path, fill, stroke): gradients are (kind, coords, [(offset, #AARRGGBB)]).
LAYERS = [
    ("glow-green", GLOW_GREEN, ("radial", (40, 58, 26), [(0, "#664EE1C3"), (1, "#004EE1C3")]), None),
    ("glow-purple", GLOW_PURPLE, ("radial", (68, 52, 26), [(0, "#667B4DFF"), (1, "#007B4DFF")]), None),
    ("green", GREEN, ("linear", (27, 33, 52, 80), [(0, "#FFC2FF7A"), (0.45, "#FF6FF0A8"), (1, "#FF2FD3B4")]), None),
    # Shade toward the fold, where the green panel passes behind the purple one.
    ("green-shade", GREEN, ("linear", (36, 50, 60, 56), [(0, "#000B3B35"), (1, "#A60B3B35")]), None),
    ("purple", PURPLE, ("linear", (70, 27, 66, 79), [(0, "#FFD88BFF"), (0.35, "#FFA04DFF"), (1, "#FF3A22D8")]), None),
    # Shadow the front panel casts along its inner edge.
    ("purple-shade", PURPLE, ("linear", (48, 50, 66, 46), [(0, "#B3180F4D"), (1, "#00180F4D")]), None),
    ("glass", GLASS, ("linear", (48, 39, 62, 72), [(0, "#BFA6F4FF"), (0.5, "#B37FC4FF"), (1, "#995E5CFF")]), None),
    # Light catching the top edges.
    ("green-rim", GREEN, None, ("linear", (27, 32, 34, 52), [(0, "#73FFFFFF"), (1, "#00FFFFFF")])),
    ("purple-rim", PURPLE, None, ("linear", (64, 26, 74, 48), [(0, "#73FFFFFF"), (1, "#00FFFFFF")])),
]
RIM_WIDTH = 0.8


def svg_color(argb):
    return f"#{argb[3:]}", int(argb[1:3], 16) / 255


def svg_gradient(gid, g):
    kind, c, stops = g
    stops_xml = "".join(
        f'<stop offset="{o}" stop-color="{svg_color(a)[0]}" stop-opacity="{svg_color(a)[1]:.2f}"/>' for o, a in stops
    )
    if kind == "linear":
        return f'<linearGradient id="{gid}" gradientUnits="userSpaceOnUse" x1="{c[0]}" y1="{c[1]}" x2="{c[2]}" y2="{c[3]}">{stops_xml}</linearGradient>'
    return f'<radialGradient id="{gid}" gradientUnits="userSpaceOnUse" cx="{c[0]}" cy="{c[1]}" r="{c[2]}">{stops_xml}</radialGradient>'


def svg():
    defs, body = [], []
    defs.append(svg_gradient("bg", ("radial", (16, 11, 86), [(0, "#294EE1C3"), (1, "#004EE1C3")])))
    for name, path, fill, stroke in LAYERS:
        attrs = []
        if fill:
            defs.append(svg_gradient(name, fill))
            attrs.append(f'fill="url(#{name})"')
        else:
            attrs.append('fill="none"')
        if stroke:
            defs.append(svg_gradient(name, stroke))
            attrs.append(f'stroke="url(#{name})" stroke-width="{RIM_WIDTH}" stroke-linejoin="round"')
        body.append(f'  <path {" ".join(attrs)} d="{path}"/>')
    return (
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108" width="512" height="512">\n'
        "  <!-- Generated by packaging/make_icon.py. -->\n"
        f'  <defs>{"".join(defs)}</defs>\n'
        '  <rect width="108" height="108" fill="#0B0B0F"/>\n  <rect width="108" height="108" fill="url(#bg)"/>\n'
        + "\n".join(body)
        + "\n</svg>\n"
    )


def android_gradient(attr, g, indent):
    kind, c, stops = g
    pad = " " * indent
    if kind == "linear":
        geo = f'android:type="linear" android:startX="{c[0]}" android:startY="{c[1]}" android:endX="{c[2]}" android:endY="{c[3]}"'
    else:
        geo = f'android:type="radial" android:centerX="{c[0]}" android:centerY="{c[1]}" android:gradientRadius="{c[2]}"'
    items = "\n".join(f'{pad}        <item android:offset="{o}" android:color="{a}" />' for o, a in stops)
    return f'{pad}<aapt:attr name="{attr}">\n{pad}    <gradient {geo}>\n{items}\n{pad}    </gradient>\n{pad}</aapt:attr>'


def vector(layers, header):
    parts = []
    for name, path, fill, stroke in layers:
        open_attrs = f'android:pathData="{path}"'
        if stroke:
            open_attrs += f' android:strokeWidth="{RIM_WIDTH}" android:strokeLineJoin="round"'
        inner = []
        if fill:
            inner.append(android_gradient("android:fillColor", fill, 8))
        if stroke:
            inner.append(android_gradient("android:strokeColor", stroke, 8))
        parts.append(f"    <!-- {name} -->\n    <path {open_attrs}>\n" + "\n".join(inner) + "\n    </path>")
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        f"<!-- {header} Generated by packaging/make_icon.py. -->\n"
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    xmlns:aapt="http://schemas.android.com/aapt"\n'
        '    android:width="108dp"\n    android:height="108dp"\n'
        '    android:viewportWidth="108"\n    android:viewportHeight="108">\n'
        + "\n".join(parts)
        + "\n</vector>\n"
    )


def monochrome():
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Single-color mark for themed icons (Android 13+). Generated by packaging/make_icon.py. -->\n"
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="108dp"\n    android:height="108dp"\n'
        '    android:viewportWidth="108"\n    android:viewportHeight="108">\n'
        f'    <path android:fillColor="#FFFFFFFF" android:pathData="{GREEN}" />\n'
        f'    <path android:fillAlpha="0.6" android:fillColor="#FFFFFFFF" android:pathData="{PURPLE}" />\n'
        "</vector>\n"
    )


def background():
    bg = [("glow", "M0,0 H108 V108 H0 Z", ("radial", (16, 11, 86), [(0, "#294EE1C3"), (1, "#004EE1C3")]), None)]
    v = vector(bg, "Ink tile with a faint teal glow.")
    # Solid ink under the glow.
    return v.replace("    <!-- glow -->", '    <path android:fillColor="#FF0B0B0F" android:pathData="M0,0 H108 V108 H0 Z" />\n    <!-- glow -->')


res = ROOT / "android/app/src/main/res"
(ROOT / "packaging/velora-icon.svg").write_text(svg())
(res / "drawable/ic_launcher_foreground.xml").write_text(vector(LAYERS, "Velora mark inside the adaptive-icon safe zone."))
(res / "drawable/ic_launcher_background.xml").write_text(background())
(res / "drawable/ic_launcher_monochrome.xml").write_text(monochrome())

# Desktop window and sidebar icon. Rasterizing needs cairosvg (pip install cairosvg).
try:
    import cairosvg

    cairosvg.svg2png(
        url=str(ROOT / "packaging/velora-icon.svg"),
        write_to=str(ROOT / "crates/client/assets/velora-icon.png"),
        output_width=256,
        output_height=256,
    )
except ImportError:
    print("cairosvg not installed: crates/client/assets/velora-icon.png not regenerated")

# Windows installer and shortcut icon, from the PNG above (pip install pillow).
try:
    from PIL import Image

    Image.open(ROOT / "crates/client/assets/velora-icon.png").convert("RGBA").save(
        ROOT / "packaging/velora.ico", sizes=[(n, n) for n in (16, 24, 32, 48, 64, 128, 256)]
    )
except ImportError:
    print("pillow not installed: packaging/velora.ico not regenerated")
print("icon written")
